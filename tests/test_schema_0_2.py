def test_0_2_nonblank_string_properties_publish_pattern_and_min_length():
    locations = (
        ("RunConditions", "evaluation_split"),
        ("RunConditions", "source_revision"),
        ("EvaluationProtocol", "protocol_id"),
        ("EvaluationProtocol", "version"),
        ("MetricDefinition", "definition_id"),
        ("MetricDefinition", "averaging"),
        ("MetricDefinition", "version"),
        ("Artifact", "dataset_id"),
    )

    for owner, name in locations:
        prop = SCHEMA_0_2["$defs"][owner]["properties"][name]
        branches = list(_string_branches(prop))
        assert branches, f"{owner}.{name} has no string branch"
        for branch in branches:
            assert branch["pattern"] == r"\S", f"{owner}.{name}"
            assert branch["minLength"] >= 1, f"{owner}.{name}"


def _string_branches(node):
    if isinstance(node, dict):
        if node.get("type") == "string":
            yield node
        for value in node.values():
            yield from _string_branches(value)
    elif isinstance(node, list):
        for item in node:
            yield from _string_branches(item)


def _nonblank_documents(value: str) -> list[dict]:
    return [
        _with_conditions({"evaluation_split": value}),
        _with_conditions({"source_revision": value}),
        _with_conditions({"evaluation_protocol": {"protocol_id": value}}),
        _with_conditions(
            {"evaluation_protocol": {"protocol_id": "p", "version": value}}
        ),
        _with_metric({"definition_id": value}),
        _with_metric({"definition_id": "d", "averaging": value}),
        _with_metric({"definition_id": "d", "version": value}),
        _doc("0.2", artifacts=[{"id": "a", "path": "a", "dataset_id": value}]),
    ]


@pytest.mark.parametrize("value", ["", "   ", "\t", "\n"])
def test_0_2_empty_or_whitespace_strings_fail_runtime_and_schema(value):
    validator = _validator(SCHEMA_0_2)

    for document in _nonblank_documents(value):
        assert not _runtime_valid(document), document
        assert not validator.is_valid(document), document


