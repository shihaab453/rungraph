def test_0_2_new_parent_and_selector_properties_are_non_null_when_present():
    assert not _nullable(SCHEMA_0_2["$defs"]["Run"]["properties"]["conditions"])
    assert not _nullable(SCHEMA_0_2["$defs"]["Artifact"]["properties"]["dataset_id"])

    conditions = SCHEMA_0_2["$defs"]["RunConditions"]["properties"]
    for name in (
        "evaluation_dataset_artifact_id",
        "model_checkpoint_artifact_id",
    ):
        assert not _nullable(conditions[name]), name
        assert conditions[name]["pattern"] == "^[A-Za-z0-9][A-Za-z0-9._:/-]*$"


def test_0_2_nested_optional_members_are_non_null_when_present():
    protocol = SCHEMA_0_2["$defs"]["EvaluationProtocol"]["properties"]
    assert not _nullable(protocol["version"])

    metric = SCHEMA_0_2["$defs"]["MetricDefinition"]["properties"]
    for name in ("higher_is_better", "averaging", "version"):
        assert not _nullable(metric[name]), name
    assert metric["higher_is_better"]["type"] == "boolean"


def test_0_2_explicit_unknown_dimensions_keep_their_null_branch():
    conditions = SCHEMA_0_2["$defs"]["RunConditions"]["properties"]
