"""Published schema 0.1/0.2 boundary (Stage 3b1).

The 0.1 artifact stays byte-for-byte the artifact generated by ``json_schema``.
0.2 has a distinct ``$id`` and publishes new nested optionals as optional but
non-null when present.
"""

from __future__ import annotations

import json
from pathlib import Path

import pydantic
import pytest
from pydantic import ValidationError

from runevidence.models import Manifest, json_schema, json_schema_0_2

REPO = Path(__file__).resolve().parents[1]
SCHEMA_0_1_PATH = REPO / "schema" / "runevidence.schema.json"
SCHEMA_0_2_PATH = REPO / "schema" / "runevidence-0.2.schema.json"

SCHEMA_0_1 = json.loads(SCHEMA_0_1_PATH.read_text(encoding="utf-8"))
SCHEMA_0_2 = json.loads(SCHEMA_0_2_PATH.read_text(encoding="utf-8"))

REGENERATE_0_1 = "regenerate with: runevidence schema -o schema/runevidence.schema.json"
REGENERATE_0_2 = "regenerate with: python -c 'from runevidence.models import json_schema_0_2; ...'"


def _semantic(node):
    """Drop the two Pydantic-version spellings the acceptance suite ignores."""
    if isinstance(node, list):
        return [_semantic(item) for item in node]
    if not isinstance(node, dict):
        return node
    out = {key: _semantic(value) for key, value in node.items()}
    if out.get("additionalProperties") is True:
        del out["additionalProperties"]
    if "const" in out and isinstance(out["const"], str) and out.get("type") == "string":
        del out["type"]
    return out


def _validator(schema: dict):
    jsonschema = pytest.importorskip("jsonschema")
    jsonschema.Draft202012Validator.check_schema(schema)
    return jsonschema.Draft202012Validator(schema)


def _runtime_valid(document: dict) -> bool:
    try:
        Manifest.model_validate(document)
    except ValidationError:
        return False
    return True


def _doc(version: str | None = "0.2", **overrides) -> dict:
    doc: dict = {
        "project": {"id": "proj", "name": "Project"},
        "runs": [{"id": "run", "metadata": {}}],
        "artifacts": [{"id": "data", "path": "data.csv", "kind": "dataset"}],
        "results": [{"id": "res", "run_id": "run", "name": "accuracy"}],
    }
    if version is not None:
        doc["schema_version"] = version
    doc.update(overrides)
    return doc


def _with_conditions(conditions) -> dict:
    doc = _doc()
    doc["runs"][0]["conditions"] = conditions
    return doc


def _with_metric(metric) -> dict:
    doc = _doc()
    doc["results"][0]["metric_definition"] = metric
    return doc


def _nullable(prop: dict) -> bool:
    if prop.get("type") == "null":
        return True
    if prop.get("type") == ["null"]:
        return True
    return any(
        option.get("type") == "null" for option in prop.get("anyOf", []) if isinstance(option, dict)
    )


# --------------------------------------------------------------- 0.1 artifact


def test_committed_0_1_schema_is_the_generated_0_1_artifact():
    assert _semantic(SCHEMA_0_1) == _semantic(json_schema()), REGENERATE_0_1


@pytest.mark.skipif(
    tuple(int(part) for part in pydantic.VERSION.split(".")[:2]) < (2, 11),
    reason="the committed 0.1 schema is spelled as Pydantic 2.11+ writes it",
)
def test_committed_0_1_schema_is_exactly_what_current_pydantic_writes():
    assert SCHEMA_0_1 == json_schema(), REGENERATE_0_1


def test_committed_0_1_schema_keeps_its_identity_and_version():
    assert SCHEMA_0_1["$id"] == "urn:runevidence:manifest:0.1"
    assert SCHEMA_0_1["properties"]["schema_version"]["const"] == "0.1"


def test_committed_0_1_schema_has_no_0_2_surface():
    props = SCHEMA_0_1["properties"]
    assert "conditions" not in SCHEMA_0_1["$defs"]["Run"]["properties"]
    assert "dataset_id" not in SCHEMA_0_1["$defs"]["Artifact"]["properties"]
    assert "metric_definition" not in SCHEMA_0_1["$defs"]["Result"]["properties"]
    for name in ("RunConditions", "EvaluationProtocol", "MetricDefinition"):
        assert name not in SCHEMA_0_1["$defs"]
    assert SCHEMA_0_1["additionalProperties"] is False
    assert SCHEMA_0_1["$defs"]["Run"]["additionalProperties"] is False
    assert "schema_version" not in SCHEMA_0_1.get("required", [])


def test_0_1_schema_rejects_every_0_2_only_key():
    validator = _validator(SCHEMA_0_1)
    assert validator.is_valid(_doc("0.1"))

    for key, mutate in (
        ("conditions", lambda d: d["runs"][0].update(conditions={})),
        ("conditions", lambda d: d["runs"][0].update(conditions=None)),
        ("dataset_id", lambda d: d["artifacts"][0].update(dataset_id="x")),
        ("dataset_id", lambda d: d["artifacts"][0].update(dataset_id=None)),
        (
            "metric_definition",
            lambda d: d["results"][0].update(metric_definition={"definition_id": "d"}),
        ),
        ("metric_definition", lambda d: d["results"][0].update(metric_definition=None)),
    ):
        document = _doc("0.1")
        mutate(document)
        assert not validator.is_valid(document), key


def test_0_1_schema_rejects_unknown_version_and_omitted_version_does_not_admit_0_2_keys():
    validator = _validator(SCHEMA_0_1)
    assert validator.is_valid(_doc(None))
    assert not validator.is_valid(_doc("0.2"))
    document = _doc(None)
    document["runs"][0]["conditions"] = {}
    assert not validator.is_valid(document)


